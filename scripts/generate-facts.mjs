#!/usr/bin/env node
/**
 * generate-facts.mjs -- scan the repository and emit prolog/generated_facts.pl
 * with the facts verify.pl checks. Purely derived from the tree; no hand-maintained truth.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const facts = new Map(); // "name/arity" -> [terms]
function topArity(args) {
  let depth = 0;
  let inAtom = false;
  let count = args.length === 0 ? 0 : 1;
  for (let i = 0; i < args.length; i++) {
    const c = args[i];
    if (inAtom) {
      if (c === "'") inAtom = false;
      continue;
    }
    if (c === "'") inAtom = true;
    else if (c === "(" || c === "[") depth++;
    else if (c === ")" || c === "]") depth--;
    else if (c === "," && depth === 0) count++;
  }
  return count;
}
function emit(term) {
  const m = term.match(/^([a-z_0-9]+)\((.*)\)\.$/s);
  if (!m) {
    out.push(term);
    return;
  }
  const key = `${m[1]}/${topArity(m[2])}`;
  if (!facts.has(key)) facts.set(key, []);
  facts.get(key).push(term);
}
const out = [
    "%% GENERATED by scripts/generate-facts.mjs -- do not edit by hand.",
];

// ---- CI facts ----
const fjDir = join(root, ".forgejo", "workflows");
const ghDir = join(root, ".github", "workflows");
const forgejoWorkflows = existsSync(fjDir)
  ? readdirSync(fjDir).filter((f) => f.endsWith(".yml") || f.endsWith(".yaml"))
  : [];
for (const wf of forgejoWorkflows) {
  emit(`forgejo_workflow('${wf}').`);
  const text = readFileSync(join(fjDir, wf), "utf8");
  const selfContained = !/^\s*uses:/m.test(text);
  const secretsReferencedOnly = !/(?:token|secret|password|api[_-]?key)\s*[:=]\s*["']?[A-Za-z0-9_\-]{16,}/i.test(
    text.replace(/\$\{\{[^}]*\}\}/g, ""),
  );
  const noInternalHosts = !/star\.intel/.test(text);
  emit(`workflow_self_contained('${wf}', ${selfContained ? "true" : "false"}).`);
  emit(`workflow_secrets_referenced_only('${wf}', ${secretsReferencedOnly ? "true" : "false"}).`);
  emit(`workflow_no_internal_hosts('${wf}', ${noInternalHosts ? "true" : "false"}).`);
}
emit(`github_workflows_present(${existsSync(ghDir) && readdirSync(ghDir).length > 0 ? "true" : "false"}).`);

// ---- www canonicalization (server must redirect www -> apex) ----
const serverMain = existsSync(join(root, "apps", "main", "server", "main.ts"))
  ? readFileSync(join(root, "apps", "main", "server", "main.ts"), "utf8")
  : "";
emit(`www_canonicalization_present(${/wwwHost[\s\S]{0,400}301|canonicalize www/s.test(serverMain) ? "true" : "false"}).`);

// ---- docs deferred ----
emit(`docs_app_present(${existsSync(join(root, "apps", "docs")) ? "true" : "false"}).`);
let docsInCi = false;
for (const wf of forgejoWorkflows) {
  const text = readFileSync(join(fjDir, wf), "utf8");
  if (/docs\.starintel\.actor/.test(text) || /docs-deploy|deploy-docs/.test(text)) docsInCi = true;
}
emit(`docs_deploy_in_ci(${docsInCi ? "true" : "false"}).`);

// ---- content manifests + provenance ----
const TARGETS = ["blog", "research", "nsaspy"];
const esc = (s) => String(s).replaceAll("'", "''").replaceAll("\\", "\\\\");
for (const target of TARGETS) {
  const manifestPath = join(root, "content", target, "manifest.json");
  if (!existsSync(manifestPath)) {
    emit(`content_manifest('${target}', absent).`);
    continue;
  }
  emit(`content_manifest('${target}', present).`);
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  for (const doc of manifest.documents) {
    const src = doc.source ?? {};
    const provenanceOk =
      typeof src.repo === "string" &&
      src.repo.length > 0 &&
      typeof src.path === "string" &&
      src.path.length > 0 &&
      typeof src.commit === "string" &&
      src.commit.length >= 7 &&
      typeof src.content_sha256 === "string" &&
      src.content_sha256.length === 64;
    emit(`published_doc('${target}', '${esc(doc.slug)}').`);
    emit(`doc_provenance_ok('${target}', '${esc(doc.slug)}', ${provenanceOk ? "true" : "false"}).`);
    if (target === "research") {
      const ap = doc.approval ?? {};
      const approvalOk =
        String(ap.state ?? "").toUpperCase() === "APPROVED" &&
        typeof ap.evidence === "string" &&
        ap.evidence.length > 0;
      emit(`research_approval_ok('${esc(doc.slug)}', ${approvalOk ? "true" : "false"}).`);
    }
    if (target === "nsaspy" && /^\d{4}-\d{2}-\d{2}$/.test(doc.slug)) {
      emit(`daily_doc('${esc(doc.slug)}').`);
      const dateMatch = String(doc.date ?? "").match(/(\d{4})-(\d{2})-(\d{2})/);
      emit(`daily_date('${esc(doc.slug)}', '${dateMatch ? dateMatch[0] : "none"}').`);
    }
  }
}

// ---- radar schema allowlist ----
const projector = existsSync(join(root, "apps", "main", "server", "projector.ts"))
  ? readFileSync(join(root, "apps", "main", "server", "projector.ts"), "utf8")
  : "";
emit(`radar_projector_present(${projector.length > 0 ? "true" : "false"}).`);
emit(`radar_fails_closed(${/unknown/.test(projector) && /fail closed|fail_closed|unrecognized/i.test(projector) ? "true" : "false"}).`);
emit(`radar_no_payload_forwarding(${!/msg\.content(?!\.length)/.test(projector) ? "true" : "false"}).`);

// ---- v0.9 required fields ----
const sdoc = existsSync(join(root, "packages", "starintel-doc", "src", "index.ts"))
  ? readFileSync(join(root, "packages", "starintel-doc", "src", "index.ts"), "utf8")
  : "";
const requiredFields = ["_id", "dataset", "dtype", "schema_version", "version", "date_added", "date_updated", "sources", "evidence", "data"];
emit(`v09_required_fields_complete(${requiredFields.every((f) => sdoc.includes(`"${f}"`)) ? "true" : "false"}).`);
emit(`v09_schema_pinned(${existsSync(join(root, "packages", "starintel-doc", "schemas", "starintel-doc-v0.9.0.schema.json")) ? "true" : "false"}).`);

// ---- importer (optional: only when the auto-dig checkout is adjacent) ----
const importer = join(root, "..", "starintel-gpt-auto-dig", "scripts", "import_starintel.py");
emit(`importer_present(${existsSync(importer) ? "true" : "false"}).`);
const backendDir = join(root, "..", "starintel-gpt-auto-dig", "backend");
emit(`autodig_backend_present(${existsSync(backendDir) ? "true" : "false"}).`);

// ---- opencode harness ----
emit(`opencode_harness_present(${existsSync(join(root, "opencode.jsonc")) && existsSync(join(root, "scripts", "enrich.mjs")) ? "true" : "false"}).`);

// ---- publishing config ----
const publishToml = existsSync(join(root, "publish.toml")) ? readFileSync(join(root, "publish.toml"), "utf8") : "";
emit(`publish_targets_configured(${/targets\.blog|^\[targets\./m.test(publishToml) ? "true" : "false"}).`);
emit(`output_repo_configurable(${/output-repo|STARINTEL_PUBLISH_OUTPUT_REPO/.test(readFileSync(join(root, "scripts", "publish.mjs"), "utf8")) ? "true" : "false"}).`);

// ---- internal hostname scan over public sources ----
function* walk(dir) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (["node_modules", ".git", "dist", "result"].includes(entry.name)) continue;
      yield* walk(full);
    } else if (/\.(html|css|js|mjs|ts|toml|json|md|org|py|pl|el)$/.test(entry.name)) {
      yield full;
    }
  }
}
let hostnameLeaks = 0;
for (const scope of ["apps", "packages", "content", "scripts", "tools"]) {
  for (const file of walk(join(root, scope))) {
    if (/[a-z0-9-]+\.star\.intel\b/.test(readFileSync(file, "utf8"))) hostnameLeaks += 1;
  }
}
emit(`internal_hostname_leaks(${hostnameLeaks}).`);

const exports = [...facts.keys()].sort().join(", ");
const lines = [
  ...out,
  `:- module(facts, [${exports}]).`,
];
for (const key of [...facts.keys()].sort()) {
  lines.push(...facts.get(key));
}
writeFileSync(join(root, "prolog", "generated_facts.pl"), lines.join("\n") + "\n");
console.log(`generated ${out.length + facts.size} lines, ${facts.size} predicates -> prolog/generated_facts.pl`);
